def test_loan_portfolio_groups_the_2023_schedule_split() -> None:
    """RIE and RIE2 share one source group, which is what keeps a series whole.

    FCA split RIE into RIE1/RIE2 at 2023Q1 while keeping every field name
    identical. Declaring them as two groups would give
    ``RIE__charge_off`` and ``RIE2__charge_off``, truncating each series
    at the split. One group maps both to one column.
    """
    dataset = get_fca_domain_dataset(domain_dataset="loan_portfolio")
    grouped = [source for source in dataset.sources if len(source.schedules) > 1]
    assert [source.schedules for source in grouped] == [("RIE", "RIE2")]


def test_loan_portfolio_code_bearing_and_name_encoded_sources() -> None:
    """The bundle carries both kinds of source, which is the point of the format.

    RC-F.1 reports the portfolio as a code. RI-E encodes it in variable
    names instead and has no code column at all.
    """
    dataset = get_fca_domain_dataset(domain_dataset="loan_portfolio")
    by_schedule = {source.schedules: source for source in dataset.sources}
    coded = by_schedule[("RCF1",)]
    name_encoded = by_schedule[("RIE", "RIE2")]

    assert coded.code_column == "LOANSTATUS"
    assert all(item.code is None for item in coded.columns.values())

    assert name_encoded.code_column is None
    assert all(item.code is not None for item in name_encoded.columns.values())
    assert name_encoded.columns["CHGOFFAGBUS"].code == 110
    assert name_encoded.columns["CHGOFFAGBUS"].column == "charge_off"


def test_loan_portfolio_keeps_reported_net_charge_offs_separate() -> None:
    """The two net-of-recoveries charge-offs map to net_charge_off, not charge_off.

    RI-E reports charge-offs gross for most portfolios but net of
    recoveries for direct loans to associations (145) and discounted
    loans to OFIs (150), which have no REC* counterpart. Landing them in
    `charge_off` would sum a net figure beside gross ones.
    """
    dataset = get_fca_domain_dataset(domain_dataset="loan_portfolio")
    columns = dataset.sources[1].columns
    assert columns["CHGOFFDLN"] == columns["CHGOFFDLN"].__class__(
        column="net_charge_off", code=145
    )
    assert columns["CHGOFFLNOFI"].column == "net_charge_off"
    assert "RECDLN" not in columns
    assert "RECLNOFI" not in columns



def test_two_source_groups_sharing_an_output_column_raises() -> None:
    """Two groups declaring one output column is a curation error, not a merge.

    Within a group, repeating a name is deliberate and maps a schedule
    split to one continuous column. Across groups it would put two
    different measures in one column, silently.
    """
    data = {
        "name": "broken",
        "code_column": "SEGMENT",
        "codes": [{"code": 1, "label": "One", "is_total": False}],
        "sources": [
            {
                "schedules": ["RCF1"],
                "code_column": "LOANSTATUS",
                "columns": {"ACCR": {"column": "balance"}},
            },
            {
                "schedules": ["RIE"],
                "code_column": None,
                "columns": {"CHGOFFRE": {"code": 1, "column": "balance"}},
            },
        ],
        "derived": [],
    }
    with pytest.raises(SchemaError, match=r"\['balance'\]"):
        DomainDataset.from_dict(data=data)



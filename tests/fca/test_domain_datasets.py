"""Tests for the curated domain dataset definitions (call_report.fca._domain_datasets).

The shipped ``loan_portfolio.json`` bundle is hand-curated rather than
generated by a script, so it has no generator to keep it honest. The drift
tests at the bottom of this module take that role: they check every
declared variable still exists in the schedule metadata this package
ships, so a field FCA renames fails the suite instead of silently
producing a null column.
"""

